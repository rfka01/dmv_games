#!/usr/bin/env python3
"""Generates src/W16TAB.C: table of Win16 imports (module, ordinal, name,
argument bytes) for DMVBD, from the Wine .spec files (ordinals and
parameter lists only). Functions that DMVBD implements are listed in
IMPL; all others get a logging stub that pops the right number of bytes.
Usage: mktab.py WINE_SPEC_DIR > src/W16TAB.C"""
import re, sys

SPECS = [('KERNEL', 'krnl386.exe16'), ('USER', 'user.exe16'), ('GDI', 'gdi.exe16'),
         ('KEYBOARD', 'keyboard.drv16'), ('SOUND', 'sound.drv16')]
ASZ = {'word': 2, 's_word': 2, 'long': 4, 'ptr': 4, 'str': 4, 'segptr': 4, 'segstr': 4}
IMPL = {
 'KERNEL': ['LocalInit', 'GlobalAlloc', 'GlobalFree', 'GlobalLock', 'GlobalUnlock',
            'LocalAlloc', 'LocalFree', 'LocalLock', 'LocalUnlock',
            'OutputDebugString', 'GetDOSEnvironment', 'FatalExit', 'FatalAppExit', 'GetVersion'],
 'USER':   ['GetCurrentTime', 'GetTickCount', 'SetRect', 'IntersectRect', 'FillRect', 'InvertRect',
            'GetKeyState', 'PeekMessage', 'PostMessage', 'GetCapture', 'LoadBitmap',
            'CopyRect', 'OffsetRect', 'InflateRect', 'IsRectEmpty', 'PtInRect', 'UnionRect', 'EqualRect',
            'GetAsyncKeyState', 'MessageBeep', 'ScrollDC', 'FrameRect'],
 'GDI':    ['BitBlt', 'PatBlt', 'SelectObject', 'CreateCompatibleDC', 'DeleteDC', 'DeleteObject',
            'GetObject', 'GetStockObject', 'CreateSolidBrush', 'CreateCompatibleBitmap',
            'SetBkColor', 'SetTextColor', 'SetBkMode', 'SetROP2', 'SetPixel', 'SetDIBitsToDevice', 'CreatePen', 'MoveTo', 'LineTo', 'Polyline', 'Ellipse', 'Rectangle'],
}

OVR = {'FatalExit': 2}

def parse(path):
    out = {}
    for l in open(path):
        m = re.match(r'\s*(\d+)\s+(pascal|stub|equate|variable)\S*\s*(?:-\S+\s+)*(\w+)?\s*(?:\(([^)]*)\))?', l)
        if not m: continue
        o, kind, name, args = int(m.group(1)), m.group(2), m.group(3) or '?', (m.group(4) or '').split()
        if name.endswith('16') and kind == 'pascal':
            pass
        nb = sum(ASZ.get(a, 2) for a in args) if kind == 'pascal' else 0
        out[o] = (name, nb, kind)
    return out

def main():
    d = sys.argv[1]
    print('/* W16TAB.C - generated by tools/mktab.py from Wine .spec ordinals. */')
    print('#include "BD.H"\n#include "W16.H"\n')
    impl = []
    for mi, (mod, f) in enumerate(SPECS):
        sp = parse(f'{d}/{f}.spec')
        n = max(sp) + 1
        arr = [255] * n
        for o, (name, nb, kind) in sp.items():
            if kind == 'pascal': arr[o] = nb
            if name in OVR: arr[o] = OVR[name]
            if name in IMPL.get(mod, []): impl.append((mi, o, name))
        print(f'static const BYTE ab_{mod}[{n}] = {{')
        for i in range(0, n, 20): print('    ' + ','.join(str(x) for x in arr[i:i+20]) + ',')
        print('};')
    names = sorted(set(x[2] for x in impl))
    for nm in names: print(f'extern void __far __pascal w16_{nm}();')
    print('const W16IMP w16tab[] = {')
    for mi, o, nm in impl: print(f'    {{ {mi}, {o}, (void (__far *)())w16_{nm} }},')
    print('    { 255, 0, 0 }\n};')
    print('const BYTE *w16argb[] = { ' + ', '.join(f'ab_{m}' for m, _ in SPECS) + ' };')
    print('const WORD w16nord[] = { ' + ', '.join(f'sizeof(ab_{m})' for m, _ in SPECS) + ' };')
    print('const char *w16mods[] = { ' + ', '.join(f'"{m}"' for m, _ in SPECS) + ', 0 };')

main()

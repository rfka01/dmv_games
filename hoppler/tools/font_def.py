F = {}
def g(ch, art):
    rows = art.split()
    assert len(rows) <= 12, (ch, len(rows))
    rows += ['......'] * (12 - len(rows))
    assert all(len(r) == 6 for r in rows), (ch, rows)
    F[ch] = rows

def x(ch, art, asc='', desc=''):
    """Kleinbuchstabe: asc = Zeilen 0-2, art = Zeilen 3-8, desc = 9-11"""
    a = asc.split() if asc else []
    a = ['......'] * (3 - len(a)) + a
    d = desc.split() if desc else []
    g(ch, ' '.join(a + art.split() + d))


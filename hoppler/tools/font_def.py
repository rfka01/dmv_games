def dots_small(src):
    r = F[src][:]; r[1] = '.#..#.'; return r
UML = {
    0x84: ('ae', dots_small('a'), False),
    0x94: ('oe', dots_small('o'), False),
    0x81: ('ue', dots_small('u'), False),
    0x8E: ('Ae', F['A'], True),
    0x99: ('Oe', F['O'], True),
    0x9A: ('Ue', F['U'], True),
    0xE1: ('ss', '.###.. #...#. #...#. #..#.. #.#... #..#.. #...#. #...#. #.##.. #.....'.split() + ['......'] * 2, False),
}

def cell(rows, capdots=False):
    """8x16-Feld, Zeilen von oben nach unten, Bit 0 = linker Punkt"""
    out = [0] * 16
    for y, r in enumerate(rows):
        v = 0
        for i, c in enumerate(r):
            if c == '#': v |= 1 << (i + 1)
        out[y + 3] = v
    if capdots:
        out[1] = (1 << 2) | (1 << 5)
    return out
